任务二：
Agent 为什么能读取文件、修改代码，而普通聊天 AI 通常不能？
Agent 接入了文件系统工具（Tool），有读取本地路径、执行命令的权限；普通聊天 AI 只在对话层交互，没有系统级访问能力。

Tool 在 Agent 中起到了什么作用？
Tool 是 Agent 与外部世界交互的接口——读文件、写文件、执行命令、调用 API 都由 Tool 完成。没有 Tool，Agent 只能"空想"不能"动手"。

为什么项目需要给 Agent 配置"员工手册"规则？
防止 Agent 乱来：比如规定只能改哪些目录、禁止执行危险命令、统一代码风格。规则 = 边界，没有边界它会替你做主，可能破坏项目。

Agent 为什么可能"忘记"之前的内容？额度怎么计算？
Agent 的上下文窗口有限，对话太长时最早的内容会被挤出去。"额度"通常按 token 消耗计费：输入 + 输出的总 token 数，不同模型单价不同。

Agent 可以随便执行终端命令会有什么风险？
rm -rf / 直接删库；curl 下载恶意脚本并执行；修改系统配置导致无法启动。本质是给了 AI 不受限的 root 权限。


